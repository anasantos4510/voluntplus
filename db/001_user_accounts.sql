CREATE TABLE IF NOT EXISTS user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clerk_user_id VARCHAR(255) NOT NULL UNIQUE,
    person_type VARCHAR(255) NOT NULL,
    active_role VARCHAR(255) NOT NULL,
    full_name VARCHAR(255),
    birth_date DATE,
    gender VARCHAR(255),
    organization_name VARCHAR(255),
    cnpj VARCHAR(255),
    organization_email VARCHAR(255),
    phone VARCHAR(255),
    availability VARCHAR(255),
    logo_url VARCHAR(255),
    description VARCHAR(4000),
    location VARCHAR(4000),
    CONSTRAINT valid_role CHECK (active_role IN ('OFFERER', 'BENEFICIARY')),
    CONSTRAINT valid_person_type CHECK (person_type IN ('INDIVIDUAL', 'ORGANIZATION')),
    CONSTRAINT organization_is_offerer CHECK (person_type <> 'ORGANIZATION' OR active_role = 'OFFERER')
);
